`timescale 1ns/1ps
// ============================================================
//  i2s_tx.v —— **标准 I2S** 串行发送器（2026-10-16 换板重写：PT8211 → MAX98357A）
//
//  它做什么：把 48 kHz 节拍上的左右声道样本，变成 DAC 要的三根线
//            BCLK（位时钟）/ LRCLK（帧时钟，本文件里叫 ws）/ DIN（数据）。
//
// ============================================================
//  ★ 为什么这次必须改（板卡从 Tang Mega 60K 换成 Tang Console 138K）
// ============================================================
//  60K：PT8211-S，格式 **LSBJ**（贴尾对齐），**WS 低 = 右声道**
//  现板：**MAX98357A**（I2S DAC + D 类功放一体），格式 **标准 I2S**
//
//  两者在**两处**不同，都会让声音出错（不是"听不出来"的那种错）：
//
//    ① **声道极性相反**：标准 I2S 是 **LRCLK 低 = 左声道**；
//       PT8211 是 WS 低 = 右声道。照抄旧代码 → **左右声道对调**。
//    ② **位对齐差 1 个 BCLK**：标准 I2S 规定"MSB 比 LRCLK 边沿**晚 1 个 BCLK**"；
//       旧实现是"窗口第 0 拍就是 MSB"（= 左对齐）。差这 1 拍 →
//       **整体位移一位**，等于把每个样本乘 2（并丢掉最低位、符号错位）。
//
// ------------------------------------------------------------
//  一、MAX98357A 规格（本地手册 `09_音频芯片_MAX98357A\MAX98357A-MAX98357B.pdf`
//      Rev 16，逐条核对过；★ = 直接影响本文件的设计）
// ------------------------------------------------------------
//   · ★ 本板用的是 **A 版**：I2S 格式（B 版才是左对齐，两者脚位相同）
//   · ★ **LRCLK 低 = 左声道**（B 版才是高 = 左）        —— Table 3
//   · ★ **MSB 先**，且从 LRCLK 边沿起**正好延迟 1 个 BCLK** —— p.19
//   · ★ **BCLK 必须是 LRCLK 的 32 / 48 / 64 倍**，LRCLK 占空比 **50 %** —— p.6
//   · ★ BCLK **上升沿**采样；发送端在下降沿更新数据最稳   —— Table 2
//   · 采样率只支持 8/16/32/44.1/48/88.2/96 kHz（48 kHz ✔；11.025/12/22.05/24 kHz ✗）
//   · DIN 对 BCLK 要 **≥10 ns** setup/hold；BCLK 高/低各 **≥15 ns** —— p.6
//   · 逻辑电平 VIH ≥ 1.3 V、VIL ≤ 0.6 V ⇒ **3.3 V LVCMOS 直驱没问题**
//   · ⚠️ **BCLK 还在跑时不能停 LRCLK**（会产生大直流输出）—— p.16
//       ⇒ 本模块**永远连续发帧**，上板不许"没声音就不发时钟"
//   · `SD_MODE`（= 底板 `PA_EN`，FPGA 侧 ball **Y14**）：
//       门限是**绝对电压**，>**1.4 V**(typ) = 左声道正常输出，<0.16 V = 关断
//       ⇒ 顶层必须给 **`PA_EN = 1'b1`**（60K 是低有效，**别照抄**）
//   · `GAIN_SLOT` 悬空（板上 R66/R67 是 DNP）⇒ 默认增益 **9 dB**
//
//  Console 上的接线（来源：Console 32001C 原理图 p.10 + SOM 30354 p.7）：
//       BCLK → `I2S_BCLK` → **Y17**；LRCLK → `I2S_LRCK` → **AB17**；
//       DIN  → `I2S_DOUT` → **AA16**；`SD_MODE` → `PA_EN` → **Y14**
//
// ------------------------------------------------------------
//  二、★ 帧结构（每帧 32 个 BCLK，每个声道 16 位）—— 逐拍推导
// ------------------------------------------------------------
//  手册没写"32× ↔ 16 位"的对应关系，但 32/48/64 × fs 对应 16/24/32 bit 是
//  这颗芯片的常规用法（树莓派 / ESP32 都是 16 位 + 32×fs 直连它），
//  且 48 kHz 的 64×fs 正是手册电气特性的测试条件。**故取 32× ⇒ 16 位**
//  （这条标为"推断"，上板用示波器一眼可验：BCLK 应为 1.536 MHz、WS 48.000 kHz）。
//
//  设 slot j = 第 j 个 BCLK（j = 0..31），WS 低占 slot 0..15（= 左声道半帧）。
//  把"MSB 晚 1 个 BCLK"落进这 32 个 slot，就得到唯一的排布：
//
//      slot 0        : 上一帧**右声道的 LSB**（跨帧进位！标准 I2S 的特征）
//      slot 1  .. 16 : 左声道 L[15] .. L[0]      ← WS 低时开始
//      slot 17 .. 31 : 右声道 R[15] .. R[1]      ← WS 高后 1 拍开始
//      （下一帧 slot 0 = 本帧 R[0]，于是右声道 16 位完整）
//
//  ⚠️ 注意 slot 0 装的是**上一帧**的右声道 LSB —— 这是"1 个 BCLK 延迟"
//     必然带来的跨帧进位，不是 bug。它正是 tb_i2s 用来判定
//     "到底有没有真的实现 1 拍延迟"的证据（左对齐实现这一位会是 0/别的东西）。
//
//  与旧版（PT8211）的对照：
//      旧：slot 0..15 = 右声道 R[15..0]，slot 16..31 = 左声道 L[15..0]，WS 低=右
//      新：整体后移 1 位 + 左右互换 + WS 低=左
//
// ------------------------------------------------------------
//  三、时钟：帧锁定 + Bresenham 均分（这套机制**不用改**，换板后依然正确）
// ------------------------------------------------------------
//  帧**由 sample_tick 直接界定**：一个采样周期里固定发 64 个半周期
//  （= 32 个 BCLK），把这 SAMPLE_DIV 拍用 Bresenham 均分给这 64 个半周期。
//  于是**帧率精确等于采样率**，不漂移、不丢样本。
//
//  实测数字（本模块 + keyboard.v 用同一个式子，只改 SYS_CLK_HZ 一处）：
//
//    SYS_CLK_HZ   SAMPLE_DIV  每半周期    BCLK        LRCK        音准误差
//    ----------   ----------  ---------   --------    ---------   ---------
//     50 MHz        1042      16/17 拍   1.5355 MHz  47.985 kHz   −0.53 音分 ✔
//    100 MHz        2083      32/33 拍   1.5360 MHz  47.999 kHz   −0.03 音分 ✔
//    150 MHz        3125      48/49 拍   1.5360 MHz  48.000 kHz     0 音分 ✔
//
//  ★ 重要更正（2026-10-16）：**音准不需要 PLL**。因为帧是锁定在 sample_tick 上的、
//    BCLK 只是把采样周期均分，所以哪怕直接用 50 MHz 晶振，LRCK 也是 47.985 kHz
//    （−0.53 音分，人耳不可闻）。**"50 MHz 分不出 1.536 MHz"只对"固定整数分频"成立**。
//    仍然推荐上 rPLL 到 150 MHz，理由有两条（都与音准无关）：
//      ① **抖动余量**：Bresenham 使 BCLK 边沿有 ±1 个系统时钟的确定性抖动
//         （50 MHz 下 ±20 ns，接近手册 12 ns(RMS) 的抖动指标；150 MHz 下 ±6.7 ns，宽松）；
//      ② **算力**：每采样周期从 1042 拍变成 3125 拍，32 声部 + 查表更从容。
//
//  ⚠️ SAMPLE_DIV 必须和 keyboard.v 里的一致。两边用同一个式子从
//     SYS_CLK_HZ/FS_HZ 推导，所以**只改 SYS_CLK_HZ 一处**即可。
//     `tb_params.v` 会实测"一帧时间 == 一个采样周期"，不一致立刻报错。
//
// ------------------------------------------------------------
//  四、与上游的握手（写给 P0-5/P0-6 的人）
// ------------------------------------------------------------
//  · `data_l` / `data_r` 在 **sample_tick 那一拍被锁存**，整帧都用锁存值。
//    上游不需要关心 BCK 相位。
//  · ⚠️ **上游必须把输出寄存**（不能是组合输出）：
//    sample_tick 那一拍抓的是"上一拍就已经稳定的值"。
//    如果混音器是组合输出，它在 tick 之后还要几拍才稳定
//    （osc_dds 的流水线是 5 拍），这一拍抓到的就是**半更新的值** → 咔哒声。
//    混音树的输出寄存器正好满足这个要求。
//  · 上电到收到第一个样本之间 sd 恒为 0（防上电"啪"一声）。
//    ⚠️ 但 BCLK/LRCLK **从复位释放后就开始跑**（手册禁止停 LRCLK）。
// ============================================================

module i2s_tx #(
    // 系统时钟频率。⚠️ 必须和 keyboard.v 的 SYS_CLK_HZ 一致
    parameter SYS_CLK_HZ = 100_000_000,
    parameter FS_HZ      = 48_000,
    // 样本位宽。MAX98357A 支持 16/24/32 位；本设计固定 16 位（配 32×fs 的 BCLK）
    parameter DATA_W     = 16
)(
    input  wire              clk,
    input  wire              rst_n,

    // 每个采样周期一个单周期脉冲
    input  wire              sample_tick,
    // 待发送的样本（二进制补码，MSB 先行）
    input  wire [DATA_W-1:0] data_l,        // 左声道
    input  wire [DATA_W-1:0] data_r,        // 右声道

    // ---- 到 DAC（Console：Y17 / AB17 / AA16）----
    output reg               bck,           // 位时钟 = 32 × fs = 1.536 MHz
    output reg               ws,            // 帧时钟 = fs，**低 = 左声道**（标准 I2S）
    output reg               sd             // 串行数据
);

    // ============================================================
    //  常量
    // ============================================================
    // 一个声道 16 个 BCK ⇒ 整帧 32 个 BCK ⇒ 64 个半周期
    localparam integer FRAME_BCK      = 2 * DATA_W;        // 32
    localparam integer HALF_PER_FRAME = 2 * FRAME_BCK;     // 64

    // 采样周期（拍数）。⚠️ 这个式子和 keyboard.v 里的 SAMPLE_DIV **必须一致**
    localparam integer SAMPLE_DIV =
        ((SYS_CLK_HZ / 1000) + (FS_HZ / 2000)) / (FS_HZ / 1000);

    // 把 SAMPLE_DIV 拍均分给 64 个半周期：
    //   基准 HP_BASE 拍，前 HP_REM 个（用 Bresenham 均匀铺开）各多 1 拍
    localparam integer HP_BASE = SAMPLE_DIV / HALF_PER_FRAME;
    localparam integer HP_REM  = SAMPLE_DIV % HALF_PER_FRAME;

    // 自检（只仿真，不进综合）
    // synthesis translate_off
    initial begin
        if (HP_BASE < 2) begin
            $display("!! i2s_tx: SAMPLE_DIV=%0d 太小（每半周期只有 %0d 拍）",
                     SAMPLE_DIV, HP_BASE);
            $display("   仿真时应把 SYS_CLK_HZ 调大，别让分频比小于 1");
            $finish;
        end
    end
    // synthesis translate_on

    // ============================================================
    //  状态
    // ============================================================
    reg        sd_bit;      // 当前该发的位（sd 口是它门控后的结果）
    reg [15:0] hp_cnt;      // 当前半周期已经数了多少拍
    reg [5:0]  ph;          // 半周期编号 0..63（ph<64 才在发帧，否则空闲）
    reg [31:0] sr;          // 移位寄存器：{data_l, data_r}，sr[31] = 当前该发的位
    reg [15:0] acc;         // Bresenham 累加器
    reg        have_sample; // 收到过样本没有（上电静音用）

    // ---- Bresenham：均匀决定本半周期要不要多 1 拍 ----
    wire [15:0] acc_tmp   = acc + HP_REM[15:0];
    wire        hp_extra  = (acc_tmp >= HALF_PER_FRAME[15:0]);
    wire [15:0] acc_next  = hp_extra ? (acc_tmp - HALF_PER_FRAME[15:0]) : acc_tmp;
    wire [15:0] hp_len    = HP_BASE[15:0] + {15'd0, hp_extra};

    wire hp_last = (hp_cnt + 16'd1 >= hp_len);   // 本拍是当前半周期的最后一拍

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            bck         <= 1'b0;
            ws          <= 1'b0;
            sd_bit      <= 1'b0;
            sr          <= 32'd0;
            ph          <= 6'd0;
            hp_cnt      <= 16'd0;
            acc         <= 16'd0;
            have_sample <= 1'b0;
        end else if (sample_tick) begin
            // -------- 帧起点：装载、复位半周期、WS 回**左**声道 --------
            //   sr = {data_l, data_r}：sr[31] = data_l[15]（左声道 MSB），
            //   移位方向朝左，所以 sr[31] 永远装着"当前该发的位"。
            //
            //   ★ 紧接着的 `sd_bit <= sr[31]` 用的是**装载前**的 sr（非阻塞赋值），
            //     此时 sr 已经在本帧内左移过 31 次，于是 sr[31] == **上一帧的 data_r[0]**
            //     —— 这正是 slot 0 要发的"跨帧进位"。**不要**改成 data_r[0]，
            //     那会把右声道 LSB 提前一帧发出去（右声道整体错位）。
            sr          <= {data_l, data_r};
            sd_bit      <= sr[31];
            bck         <= 1'b0;            // 与上一拍合起来构成最后一个 BCK 的下降沿
            ws          <= 1'b0;            // 帧头 = **左**声道（标准 I2S）
            ph          <= 6'd0;
            hp_cnt      <= 16'd0;
            acc         <= 16'd0;
            have_sample <= 1'b1;
        end else if (ph < HALF_PER_FRAME) begin
            //   ⚠️ 这里必须拿 ph 和**完整位宽的** HALF_PER_FRAME(64) 比，
            //      不能写 HALF_PER_FRAME[5:0] —— 64 在 6 位里是 0，
            //      写成切片就变成 `ph < 0`（恒假），**整帧永远发不出去**。
            if (hp_last) begin
                hp_cnt <= 16'd0;
                bck    <= ~bck;             // 翻转 → 上升沿 / 下降沿
                ph     <= ph + 6'd1;
                acc    <= acc_next;         // 每个半周期都推进 Bresenham
                if (bck) begin
                    // ---- 下降沿：把下一位摆上总线 ----
                    //   `sr <= {sr[30:0],1'b0}` 与 `sd_bit <= sr[31]` 是同一拍的非阻塞赋值，
                    //   sr[31] 读的是**移位前**的最高位 —— 正好是移完之后的新 MSB。
                    //   这样下一个上升沿（半个 BCK 之后）采到的就是正确的下一位，
                    //   离上升沿有 ≥ 半个 BCLK 的建立时间（50 MHz 下 ≥ 320 ns ≫ 手册要求的 10 ns）。
                    sd_bit <= sr[31];
                    sr     <= {sr[30:0], 1'b0};
                    //  左声道发完后（slot 15 结束，即 ph=31 结束）切到右声道。
                    //  WS 与 BCLK 下降沿**同拍**变化 —— 标准 I2S 的做法；
                    //  右声道 MSB 因此比 WS 边沿晚正好 1 个 BCLK（slot 17 才出现）。
                    if (ph == 6'd31) ws <= 1'b1;
                end
            end else begin
                hp_cnt <= hp_cnt + 16'd1;
            end
        end
        // ph >= 64：本帧 32 个 BCK 已经发完，保持不动等下一个 sample_tick。
        //   **故意硬性截断在 64 个半周期**：万一 SAMPLE_DIV 配错，
        //   也只是帧尾多一段空闲，而不会把帧发成 33/31 个 BCK。
    end

    // ============================================================
    //  上电静音：收到第一个样本之前输出 0，
    //  否则移位寄存器里的未初始化内容会在上电时"啪"一声。
    //
    //  ⚠️ 用一个**独立的**内部 reg `sd_bit` 承载移位结果，
    //     输出口 `sd` 只在这一个 always 块里被赋值。
    //     曾经把 `sd` 同时写在主状态机里和这里 → 同一个 reg 两个驱动源
    //     （仿真里是竞争、综合直接报多驱动）。
    //
    //  多出来的这 1 拍延迟无害：数据在下降沿后马上就稳，离下一个上升沿还远。
    // ============================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) sd <= 1'b0;
        else        sd <= have_sample ? sd_bit : 1'b0;
    end

endmodule
