`timescale 1ns/1ps
// ============================================================
//  osc_dds.v —— 一个 DDS 振荡器（P0-3）★ 整个项目的核心
//
//  它做什么：把"频率字"变成"波形的采样点"。
//
//      freq_word  →  32 位相位累加器  →  相位  →  查波表 + 线性插值  →  采样点
//
//  赛题口径上，**一个这样的模块 = 一个独立振荡器**
//  （独立相位累加器 + 频率调控 + 包络控制里的前两项都在这里）。
//  所以这个模块会被例化很多份：分音、FM 算子、每个声部……
//
// ------------------------------------------------------------
//  一、为什么必须是"累加器在本模块内部"
// ------------------------------------------------------------
//  A0 把 `keyboard.v` 的 `phase_out` 删掉了，就是为了这个：
//  加法合成要 8 个分音**各自**的相位、FM 要调制器**自己**的相位，
//  共用一条相位在结构上做不到（所有分音会同相，加法等于白做）。
//  所以 `keyboard.v` 只给"该用多大频率"，相位由本模块自己推。
//
// ------------------------------------------------------------
//  二、相位字 → 频率的换算（全项目的量纲基准）
// ------------------------------------------------------------
//      freq_word = round(f × 2^32 / fs)      fs = 48 kHz
//      相位每采样前进 freq_word，2^32 对应**正好一个周期**
//      即：  f = freq_word × fs / 2^32
//  对照值（fs=48 kHz，来自 freq_table.v）：
//      MIDI 60 (C4, 261.63 Hz) → 23,409,859
//      MIDI 48 (C3, 130.81 Hz) → 11,704,930
//  相位高 10 位 = 波表地址（1024 点），低 22 位 = 插值权重
//
// ------------------------------------------------------------
//  三、流水线：5 级，LATENCY = 5 拍
// ------------------------------------------------------------
//   第 0 拍  sample_tick=1，同时寄存器里预算出下一相位
//   第 1 拍  addr_a_r / addr_b_r / frac_r 给到 ROM
//   第 2 拍  ROM 输出 y0 / y1（ROM 自带 1 拍延迟，见 P0-2）
//   第 3 拍  delta = y1-y0 锁存；y0 与 frac 跟着往下走
//   第 4 拍  乘法器输出 prod = delta × frac（DSP）
//   第 5 拍  采样点输出，同时 sample_valid 拉高
//
//  ⚠️ **sample_tick 的周期必须 ≥ LATENCY（5 拍）**。
//     这是所有流水线设计的固有限制：输入（频率字/节拍）必须在整条
//     流水线走完之前保持不变。真实设计里 100 MHz / 48 kHz = **2083 拍**，
//     余量 400 倍，完全不用担心；但**仿真里如果把节拍调得太密就会出错**，
//     这也是 tb_osc.v 里 SIM_DIV 取 16 而不是 4 的原因。
//
//  ⚠️ 输出比"当拍相位"晚 5 拍是**恒定的**，音频上完全无影响
//     （5 拍 = 50 ns）。**但绝不能让它随条件变化** —— 拍数一变，
//     混音时就对不齐了。所以 sample_valid 也是用同一深度的移位链产生。
//
// ------------------------------------------------------------
//  四、插值为什么能到 60 dB 以上（验收指标）
// ------------------------------------------------------------
//  三个误差源，都算了：
//    ① 表量化：12 位表，满量程正弦的 SNR = 6.02×12 + 1.76 ≈ **74 dB**
//       —— 这是主导项，也是这个设计的理论上限
//    ② 线性插值误差：1024 点表的二阶项 ≈ (2π/1024)²/8 = 4.7e-6
//       → 约 −106 dB，可以忽略
//    ③ 乘法取整：frac 取 18 位（2^-18）
//       → 误差 ≤ 4095/262144 = 0.016 LSB → 约 −90 dB，可忽略
//  三条加起来仍然是 **~74 dB**（被①压住），比要求的 60 dB 高 14 dB。
//
//  ⚠️ frac 只取相位小数的**高 18 位**（丢掉低 4 位），这不是偷懒：
//     12 位 × 18 位 = **正好一个 18×18 DSP**；用满 22 位就要两个 DSP，
//     而多出来的精度（2^-22）远低于表本身的量化噪声，纯属浪费。
//
// ------------------------------------------------------------
//  五、门控 gate 是临时措施，正式版由 ADSR/VCA 负责
// ------------------------------------------------------------
//  gate=0 时：相位**冻结**、输出**清零**。
//  这只是为了"还没写 ADSR 之前也能静音"（P0-7 要出声验证时用得上）。
//  正式结构里振荡器是**自由运行**的（相位一直在走，相位随机反而让
//  和弦更好听），声音的有无由包络控制 —— 到 P1 时 gate 直接接 1'b1。
//
// ------------------------------------------------------------
//  六、⚠️ 一个必须在 P1 处理的资源问题（现在先不管）
// ------------------------------------------------------------
//  本模块内部例化了 `wavetable_rom`（3 个 BSRAM 块）。
//  一个振荡器 3 块，32 个声部就是 96 块 —— **刚好卡在 118 块的边缘**，
//  而加法/FM 要 ~96 个振荡器，那样需要 288 块，**根本装不下**。
//
//  正解（P1-1 做）：波表是**只读且所有声部共用**的，
//  应该**把 ROM 提出来做成一个共享的时分复用查表器**：
//      100 MHz ÷ 48 kHz = 2083 拍/采样，32 声部 × 2 次读 × 几拍 ≈ 几百拍
//      余量极大，一个 ROM + 一个插值器就能伺候全部声部。
//  那时 osc_dds 拆成两半：
//      · **相位累加器** 留在每个声部内部（赛题按这个计数，绝对不能合并！）
//      · 查表 + 插值 变成共享流水线（按声部轮转）
//  现在把这件事记在跟踪表里，P0/P1 边界上再做。
//
//  依赖：P0-2 `wavetable_rom.v` ✅、A0 `keyboard.v` 的 freq_word 接口 ✅
// ============================================================

module osc_dds #(
    // ---- 相位与频率 ----
    parameter PHASE_W  = 32,        // 相位累加器位宽（同时是 freq_word 位宽）
    // ---- 波表 ----
    parameter TABLE_AW = 10,        // 表内地址位宽：2^10 = 1024 点
    parameter WAVE_W   = 2,         // 波形选择位宽：2^2 = 4 种波形
    parameter BITS     = 12,        // 波表位宽（偏移二进制，中心 2048）
    parameter INIT_FILE = "wavetable_all.hex",
    // ---- 插值 ----
    parameter FRAC_W   = 18,        // 插值权重位宽（取相位小数的高 FRAC_W 位）
    // ---- 输出 ----
    parameter OUT_W    = 16,        // 输出位宽（有符号，已居中）
    // ---- 流水线 ----
    parameter LATENCY  = 5,
    // ---- FM 相位调制输入（A2 `fm_op.v` 用）----
    //  0 = 关闭（默认）：本模块行为与 P0-3 版本**逐位相同**
    //      —— phase_off_m 变成常量 0，综合会把那个加法器优化掉。
    //  因为默认关闭，原有的 tb（不连 phase_offset）继续有效。
    parameter PHASE_MOD_EN = 0
)(
    input  wire                    clk,
    input  wire                    rst_n,

    // ---- 48 kHz 采样节拍（单周期脉冲）----
    //   ⚠️ 周期必须 ≥ LATENCY，见文件头"三"
    input  wire                    sample_tick,

    // ---- 门控：0 = 静音并冻结相位（临时措施，正式版接 1'b1）----
    //  ⚠️⚠️ **绝对不能和 adsr.v 的 gate 接同一个信号**（顶层连线时最容易犯）
    //
    //   本模块 gate=0 → 相位冻结 + **输出清零**；
    //   而 adsr 的 gate=0 → 进入 RELEASE，用 314 ms 慢慢衰减。
    //   若把同一个 note_on 同时接给两者（这是最自然的写法），
    //   松键瞬间振荡器输出就变 0 → **释放尾音被清零吃掉** →
    //   ADSR 的 Release 完全失效，听感上"松键即静音"，白做了。
    //
    //   ⇒ 正式结构里振荡器是**自由运行**的：**本端口接 `1'b1`**，
    //     声音的有无完全由 adsr + vca 决定。
    input  wire                    gate,

    // ---- 来自 keyboard.v 的频率字（已含滑音 + 颤音）----
    input  wire [PHASE_W-1:0]      freq_word,

    // ---- 音色选择：0=sine 1=square 2=sawtooth 3=triangle ----
    input  wire [WAVE_W-1:0]       wave_sel,

    // ---- FM 用的相位偏移（PHASE_MOD_EN=1 时有效）----
    //  ⚠️ 这是**相位调制（PM）**：只加到"查表用的相位"上，
    //     **不进相位累加器**。若把它加进累加器，相位等于被积分一次，
    //     那就变成了频率调制（FM），频谱和听感都不同 ——
    //     DX7 那一类电琴用的正是 PM，所以别改。
    //  PHASE_MOD_EN=0 时本端口不参与任何运算，可以不接（悬空无害）。
    input  wire [PHASE_W-1:0]      phase_offset,

    // ---- 输出：有符号、居中的采样点 ----
    //
    //  ⚠️⚠️ 给 P0-5 `vca.v` 的接口警告（**必须在乘法里显式处理符号**）
    //
    //    本信号是 **signed**，而 `adsr.v` 的 `gain` 是 **unsigned**。
    //    Verilog 的规则是"只要有一个操作数无符号，整个表达式就是无符号"，
    //    有符号操作数会被**零扩展**。实测：
    //        reg signed [15:0] s = -100;  reg [15:0] u = 1000;
    //        m32 = s * u;      // 得到 65436000，而不是 -100000
    //    ⇒ 直接写 `sample_out * gain` 会**把负半周全部毁掉**
    //      （波形只剩正半周，还叠加巨大直流）。
    //
    //    正确写法（先各自显式拓宽成有符号再乘）：
    //        wire signed [31:0] sa = $signed({{16{sample_out[15]}}, sample_out});
    //        wire signed [31:0] ga = $signed({16'b0, gain});       // gain 恒非负
    //        wire signed [31:0] p  = sa * ga;                      // 有符号乘法 ✔
    //        // 取 p >>> 16（右移 16 位到 16 位量程），再做饱和
    //    ⚠️ 这和 P0-3 那个"frac 被声明成 signed"是同一类陷阱，
    //      而且**两个模块各自的 tb 都抓不到**（各自单独例化），
    //      只有顶层连起来才会爆 —— 所以 vca.v 必须专门喂一个负样本做测试。
    output reg  signed [OUT_W-1:0] sample_out,
    output wire                    sample_valid
);

    // 相位里"表地址之外"的位数 = 小数部分总位宽（32 - 10 = 22）
    localparam FRAC_TOTAL = PHASE_W - TABLE_AW;

    // 位宽自检（只仿真，不进综合）——参数改了但没同步改另一个时立刻报出来，
    // 免得又出现"地址高位被静默裁掉"那种要到上板才发现的错
    // synthesis translate_off
    initial begin
        if (FRAC_W > FRAC_TOTAL) begin
            $display("!! osc_dds: FRAC_W=%0d 超过相位小数位宽 %0d", FRAC_W, FRAC_TOTAL);
            $finish;
        end
        if (OUT_W < BITS) begin
            $display("!! osc_dds: OUT_W=%0d 比波表位宽 %0d 还小，输出会削顶", OUT_W, BITS);
            $finish;
        end
    end
    // synthesis translate_on

    // ============================================================
    //  1) 相位累加器 —— **振荡器的心脏，赛题就数它**
    //
    //  32 位无符号数，加满自然回绕（Verilog 位宽就是回绕，不用写 if）。
    //  ⚠️ 不要改成"门控时钟"（用 clk & tick 当时钟）：
    //     那是门控时钟，会引入时钟偏差、时序分析也不认；
    //     正确做法就是这里这样，用 enable（tick）当条件。
    // ============================================================
    reg [PHASE_W-1:0] phase;

    // 下一相位：累加器用它，同时**直接**用它取地址
    //   （多一个 32 位加法器换来的好处：第 n 个样本对应相位 n×freq_word，
    //     量纲干净，Python 参考模型能一行对上；32 个 LUT 换清晰度，值）
    wire [PHASE_W-1:0] phase_next = phase + freq_word;

    // FM 相位偏移（PHASE_MOD_EN=0 时是常量 0 → 与原实现逐位相同）
    wire [PHASE_W-1:0] phase_off_m = PHASE_MOD_EN ? phase_offset
                                                  : {PHASE_W{1'b0}};

    // ★ **查表用的相位** = 累加器的下一相位 + 相位偏移。
    //     注意它只影响查表，**不回写累加器** —— 这才是相位调制。
    wire [PHASE_W-1:0] phase_idx   = phase_next + phase_off_m;

    // ============================================================
    //  2) 第 1 级：把地址和小数锁进寄存器，交给 ROM
    //
    //  地址必须**寄存**再给 ROM，不能直接拿 phase 的组合输出去接：
    //  ROM 内部是"地址→寄存器→输出"，地址在时钟沿进来，
    //  组合路径上多绕一层逻辑只会让时序更紧，没有任何好处。
    // ============================================================
    reg  [TABLE_AW-1:0] addr_a_r;
    reg  [TABLE_AW-1:0] addr_b_r;

    // ⚠️⚠️ frac **绝对不能声明成 signed**（这里栽过，P0-3 的主 bug）
    //
    //  frac 是插值权重，取值 0 ~ 2^18-1，**恒为非负**。
    //  我当初为了"让乘法变成有符号乘法"顺手写了 `reg signed [17:0] frac_r`，
    //  结果 frac ≥ 2^17（也就是一半的采样点）在 signed 眼里是**负数**：
    //      frac = 196608（= 3×65536）  被当成  -65536
    //  于是那一半采样点的插值**方向反了** —— 实测 SINAD 只有 50 dB，
    //  比"完全不插值"（55 dB）还差，而且波形会冲出波表的取值范围。
    //
    //  正确的做法：**保持 frac 无符号**，在**相乘的那一步**把它零扩展进
    //  一个有符号的容器里（见下面 frac_s），这样既是有符号乘法、
    //  数值又不会被误读。
    //
    //  这也是 Verilog 的经典陷阱：**符号性要靠"拓宽 + 补 0/补符号"来给，
    //  不能靠把一个本来就非负的量声明成 signed 来给。**
    reg  [FRAC_W-1:0] frac_r;
    reg  [FRAC_W-1:0] frac_d1;
    reg  [FRAC_W-1:0] frac_d2;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            phase    <= {PHASE_W{1'b0}};
            addr_a_r <= {TABLE_AW{1'b0}};
            addr_b_r <= {TABLE_AW{1'b0}};
            frac_r   <= {FRAC_W{1'b0}};
        end else if (sample_tick && gate) begin
            phase    <= phase_next;

            // 地址 = 相位高 10 位
            addr_a_r <= phase_idx[PHASE_W-1 -: TABLE_AW];

            // ⚠️ addr_b = addr_a + 1 **靠 10 位加法自然回绕**。
            //    1023 + 1 = 0（1024 装不下就溢出了），正好指向本周期的第 0 点，
            //    这正是周期波形要的。**不要**写 if (addr_a == 1023) addr_b = 0。
            addr_b_r <= phase_idx[PHASE_W-1 -: TABLE_AW] + 1'b1;

            // 小数权重 = 相位低 22 位里的**高 18 位**（无符号，见上面 frac_r 的说明）
            frac_r   <= phase_idx[FRAC_TOTAL-1 -: FRAC_W];
        end
    end

    // ============================================================
    //  3) 第 2 级：查表（ROM 自带 1 拍延迟）
    // ============================================================
    wire [BITS-1:0] y0_rom;      // 第 n 个点（偏移二进制 0~4095）
    wire [BITS-1:0] y1_rom;      // 第 n+1 个点

    wavetable_rom #(
        .TABLE_LEN (1 << TABLE_AW),
        .BITS      (BITS),
        .WAVE_NUM  (1 << WAVE_W),
        .INIT_FILE (INIT_FILE),
        .ADDR_W    (TABLE_AW),
        .WAVE_W    (WAVE_W)
    ) u_rom (
        .clk      (clk),
        .addr_a   (addr_a_r),
        .data_a   (y0_rom),
        .addr_b   (addr_b_r),
        .data_b   (y1_rom),
        .wave_sel (wave_sel)
    );

    // ============================================================
    //  4) 第 3 级：算斜率 delta = y1 - y0，同时把 y0 和 frac 往后带
    //
    //  delta 范围：-4095 ~ +4095 → 13 位有符号刚好装下。
    //  ⚠️ 两个操作数都要**显式**声明成有符号再相减：
    //     y1_rom 本身是无符号的（偏移二进制），
    //     不转有符号直接相减，负数会变成绕回来的巨大正数。
    // ============================================================
    reg  signed [BITS:0]     delta_r;      // 13 位有符号
    reg        [BITS-1:0]    y0_d1;        // y0 往后带（两级，共 2 拍）
    reg        [BITS-1:0]    y0_d2;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            delta_r <= {(BITS+1){1'b0}};
            frac_d1 <= {FRAC_W{1'b0}};
            frac_d2 <= {FRAC_W{1'b0}};
            y0_d1   <= {BITS{1'b0}};
            y0_d2   <= {BITS{1'b0}};
        end else begin
            delta_r <= $signed({1'b0, y1_rom}) - $signed({1'b0, y0_rom});
            // frac 往后带两级，第 4 拍和 prod 对齐。
            // ⚠️ 这两行**不能删**：删掉之后 frac_d1/frac_d2 没有任何驱动源，
            //    仿真里会一直是 x（乘法结果全 x、输出全 X）。
            //    我在改 signed 那个 bug 时顺手把这两行删了，正好踩了一次。
            frac_d1 <= frac_r;
            frac_d2 <= frac_d1;
            y0_d1   <= y0_rom;
            y0_d2   <= y0_d1;
        end
    end

    // ============================================================
    //  5) 第 4 级：一次乘法器算完插值（走 DSP）
    //
    //      prod = delta × frac          （13 位有符号 × 19 位有符号）
    //      插值量 = round(prod / 2^18)
    //
    //  ⚠️ frac_s 的读法（这是本模块最容易写错的一行）：
    //     · frac_d2 本身是**无符号**的 0 ~ 2^18-1（权重，永远非负）
    //     · 前面补一个 0 变成 **19 位**，再声明为有符号
    //       → 最高位恒为 0，所以它的有符号值**就是**它本身，不会变负
    //     · 这样两个操作数都是有符号的 → Verilog 做有符号乘法 ✓
    //
    //     反过来的错误写法（我踩过的）是把 frac 直接声明成 signed：
    //       frac ≥ 2^17 就被当成负数，一半的采样点插值方向反转。
    //
    //     位宽核对：|delta| ≤ 4095，frac ≤ 262143
    //              |prod| ≤ 4095 × 262143 = 1.0737e9 < 2^31  ✔ 32 位有符号装得下
    //
    //  (* multstyle = "dsp" *) 不能省：不写的话综合器可能把 13×19
    //  塞进普通逻辑（几百个 LUT），而我们有一百多个 DSP 空着。
    //  寄存器紧跟在乘法后面，正好对应 DSP 内部那级输出寄存器。
    // ============================================================
    wire signed [FRAC_W:0] frac_s = {1'b0, frac_d2};   // 19 位有符号，恒为正

    reg  signed [31:0] prod_r;

    (* multstyle = "dsp" *)
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) prod_r <= 32'sd0;
        else        prod_r <= delta_r * frac_s;
    end

    // 四舍五入：加半个 LSB 再右移。
    //   为什么要舍入而不是直接截断：截断的误差是**单边**的（永远偏小），
    //   会在波形上叠加一个跟信号相关的小锯齿，频谱上抬高低次谐波，
    //   SINAD 会掉几个 dB。加半个 LSB 后误差变成对称的，白赚。
    //   >> 用算术右移（>>>），负数才是"向下取整"的正确行为。
    wire signed [31:0] prod_round = prod_r + 32'sd131072;   // 2^17 = 半个 2^18
    wire signed [31:0] interp     = prod_round >>> FRAC_W;

    // ============================================================
    //  6) 第 5 级：y0 + 插值量 → 居中 → 放大到输出位宽
    //
    //  ⚠️ 这里每一步都在跟 Verilog 的**位宽陷阱**打交道，写清楚：
    //
    //    mix32 = y0 + interp            ∈ [0, 4095]（数学上不会出界，
    //                                     因为插值点一定在 y0 和 y1 之间）
    //    减中心 2048                    ∈ [-2048, 2047]     ← 变成有符号
    //    左移 (OUT_W - BITS) 位          ∈ [-32768, 32752]  ← 16 位装得下
    //
    //  ⚠️ **不能在窄位宽里左移**：`centered13 << 4` 里的 4 位会被
    //     "表达式宽度 = 操作数宽度 = 13" 这条规则直接丢掉（本项目在
    //     keyboard.v 的颤音上已经栽过一次，那次是频率字恰好翻倍）。
    //     所以先在 32 位里算完，最后再截到 OUT_W —— 此时值域已在
    //     16 位之内，低 16 位就是正确的补码表示（tb_osc.v 里会验范围）。
    // ============================================================
    wire signed [31:0] mix32      = $signed({{(32-BITS){1'b0}}, y0_d2}) + interp;
    wire signed [31:0] centered32 = mix32 - 32'sd2048;
    wire signed [31:0] scaled32   = centered32 << (OUT_W - BITS);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) sample_out <= {OUT_W{1'b0}};
        else        sample_out <= gate ? scaled32[OUT_W-1:0] : {OUT_W{1'b0}};
    end

    // ============================================================
    //  7) sample_valid：和 sample_out **同一条流水线**的标记
    //
    //  用移位链把 sample_tick 往后推 LATENCY 拍，而不是"再打几拍试试"。
    //  这样只要改 LATENCY 一个参数，标记和数据就永远对齐 ——
    //  下游（混音器）靠这个脉冲知道"这一拍是新的采样点"。
    // ============================================================
    reg [LATENCY-1:0] valid_sr;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) valid_sr <= {LATENCY{1'b0}};
        else        valid_sr <= {valid_sr[LATENCY-2:0], sample_tick};
    end

    assign sample_valid = valid_sr[LATENCY-1];

endmodule
